from __future__ import annotations

import argparse
import logging
import sys
from collections.abc import Sequence

from sadi.doctor import exit_code, run
from sadi.doctor.registry import all_checks
from sadi.doctor.render_text import render
from sadi.doctor.schema import Layer, Os, RunOptions
from sadi.logging_setup import get_logger

_log = get_logger(__name__)

EXIT_USAGE = 64
EXIT_CRASH = 70


def _out(text: str) -> None:
    """Write to stdout."""
    sys.stdout.write(text)


def _err(text: str) -> None:
    """Write to stderr."""
    sys.stderr.write(text)


def _parser() -> argparse.ArgumentParser:
    """Build the argument parser."""
    p = argparse.ArgumentParser(prog="sadi-doctor", description="Check this machine for SADI.")
    p.add_argument("command", nargs="?", default="run", choices=["run", "list", "explain", "docs"])
    p.add_argument("target", nargs="?", help="check id for `explain`")
    p.add_argument(
        "--check", action="append", metavar="ID", help="run only this check (repeatable)"
    )
    p.add_argument("--layer", action="append", choices=[x.value for x in Layer])
    p.add_argument("--skip", action="append", metavar="ID", help="skip this check (repeatable)")
    p.add_argument("--json", action="store_true", help="emit the report as JSON")
    p.add_argument("--verbose", action="store_true", help="show remediation for passes too")
    p.add_argument(
        "--os", dest="render_os", choices=[x.value for x in Os], help="write fixes for this OS"
    )
    p.add_argument("--data-root", help="data directory to inspect")
    p.add_argument("--api-port", type=int, default=8000)
    p.add_argument("--port", help="serial port of the device to probe (default: first found)")
    p.add_argument(
        "--stream-seconds",
        type=int,
        default=0,
        metavar="N",
        help="stream from the device for N seconds (enables DEV-040)",
    )
    p.add_argument(
        "--with-reset",
        action="store_true",
        help="reset the device and time the boot (enables DEV-050)",
    )
    return p


def _list() -> int:
    """Print the catalog."""
    for spec, _ in all_checks():
        _out(f"{spec.id:9} {spec.severity.value:8} {spec.title}\n")
    return 0


def catalog_markdown() -> str:
    """Render the check catalog as Markdown (source of docs/doctor-checks.md)."""
    lines = [
        "# Doctor check catalog",
        "",
        "Status: generated",
        "",
        "Generated by `sadi-doctor docs`; do not edit.",
        "",
    ]
    for spec, _ in all_checks():
        lines += [
            f"## {spec.id} - {spec.title}",
            "",
            f"- Layer: {spec.layer.value}",
            f"- Severity: {spec.severity.value}",
        ]
        lines += [f"- Detection: {spec.detection}", "- Failure modes:"]
        lines += [f"  - `{mode}`: {desc}" for mode, desc in spec.modes.items()]
        lines.append("")
    return "\n".join(lines)


def _explain(check_id: str | None) -> int:
    """Print one check's modes and detection."""
    for spec, _ in all_checks():
        if spec.id == check_id:
            _out(f"{spec.id} - {spec.title}\nDetection: {spec.detection}\nFailure modes:\n")
            for mode, desc in spec.modes.items():
                _out(f"  {mode}: {desc}\n")
            return 0
    _err(f"unknown check id {check_id!r}; run `sadi-doctor list`\n")
    return EXIT_USAGE


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point; returns the process exit code."""
    logger = logging.getLogger("sadi")
    saved = logger.level
    try:
        return _main(argv)
    finally:
        logger.setLevel(saved)


def _main(argv: Sequence[str] | None) -> int:
    """Parse arguments and dispatch."""
    try:
        args = _parser().parse_args(argv)
    except SystemExit as e:
        return EXIT_USAGE if e.code else 0
    logging.getLogger("sadi").setLevel(logging.WARNING)
    if args.command == "list":
        return _list()
    if args.command == "docs":
        _out(catalog_markdown())
        return 0
    if args.command == "explain":
        return _explain(args.target)
    options = RunOptions(
        checks=tuple(args.check) if args.check else None,
        layers=tuple(Layer(x) for x in args.layer) if args.layer else None,
        skip=tuple(args.skip or ()),
        render_os=Os(args.render_os) if args.render_os else None,
        data_root=args.data_root,
        api_port=args.api_port,
        port=args.port,
        stream_seconds=args.stream_seconds,
        with_reset=args.with_reset,
    )
    try:
        result = run(options)
    except Exception:  # noqa: BLE001 - last resort: tell the user, exit 70
        _log.exception("doctor crashed")
        _err("sadi-doctor crashed; see the log. This is a bug in the doctor.\n")
        return EXIT_CRASH
    if result.is_err:
        _err(f"{result.err.value}\n")
        return EXIT_USAGE
    report = result.unwrap()
    _out(
        report.model_dump_json(indent=2) + "\n"
        if args.json
        else render(report, verbose=args.verbose)
    )
    return exit_code(report)


if __name__ == "__main__":
    raise SystemExit(main())
