def _list() -> int:
    """Print the catalog."""
    for spec, _ in all_checks():
        _out(f"{spec.id:9} {spec.severity.value:8} {spec.title}\n")
    return 0


def catalog_markdown() -> str:
    """Render the check catalog as Markdown (source of docs/doctor-checks.md)."""
    lines = [
        "# Doctor check catalog",
        "",
        "Status: generated",
        "",
        "Generated by `sadi-doctor docs`; do not edit.",
        "",
    ]
    for spec, _ in all_checks():
        lines += [
            f"## {spec.id} - {spec.title}",
            "",
            f"- Layer: {spec.layer.value}",
            f"- Severity: {spec.severity.value}",
        ]
        lines += [f"- Detection: {spec.detection}", "- Failure modes:"]
        lines += [f"  - `{mode}`: {desc}" for mode, desc in spec.modes.items()]
        lines.append("")
    return "\n".join(lines)


def _explain(check_id: str | None) -> int:
    """Print one check's modes and detection."""
    for spec, _ in all_checks():
        if spec.id == check_id:
            _out(f"{spec.id} - {spec.title}\nDetection: {spec.detection}\nFailure modes:\n")
            for mode, desc in spec.modes.items():
                _out(f"  {mode}: {desc}\n")
            return 0
    _err(f"unknown check id {check_id!r}; run `sadi-doctor list`\n")
    return EXIT_USAGE


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point; returns the process exit code."""
    logger = logging.getLogger("sadi")
    saved = logger.level
    try:
        return _main(argv)
    finally:
        logger.setLevel(saved)


def _main(argv: Sequence[str] | None) -> int:
    """Parse arguments and dispatch."""
    try:
        args = _parser().parse_args(argv)
    except SystemExit as e:
        return EXIT_USAGE if bool(e.code) else 0
    logging.getLogger("sadi").setLevel(logging.WARNING)
    if args.command == "list":
        return _list()
    if args.command == "docs":
        _out(catalog_markdown())
        return 0
    if args.command == "explain":
        return _explain(args.target)
    options = _options(args)
    if args.command == "fix":
        return _fix(args, options)
    return _run(args, options)


def _options(args: argparse.Namespace) -> RunOptions:
    """Build RunOptions from parsed arguments."""
    return RunOptions(
        checks=tuple(args.check) if args.check else None,
        layers=tuple(Layer(x) for x in args.layer) if args.layer else None,
        skip=tuple(args.skip or ()),
        render_os=Os(args.render_os) if args.render_os else None,
        data_root=args.data_root,
        api_port=args.api_port,
        running=args.running,
        port=args.port,
        stream_seconds=args.stream_seconds,
        ad3_open=args.ad3_open,  # frob:ticket 01M6Z1E0F6PK6K2F6B9VC7QQWM
        with_reset=args.with_reset,
        open_browser=args.open_browser,  # frob:ticket 01M6WJHVZC0JYPV6W1CCFWSS8S
    )


def _budget(args: argparse.Namespace, options: RunOptions) -> Budget:
    """Build the run Budget from --timeout/--check-timeout over the defaults."""
    base = Budget.for_deep(options.deep)
    return Budget(
        check_timeout_s=args.check_timeout or base.check_timeout_s,
        run_timeout_s=args.timeout or base.run_timeout_s,
        workers=base.workers,
    )


def _fix(args: argparse.Namespace, options: RunOptions) -> int:
    """Dispatch `fix`: dry run unless --apply."""
    if not args.target:
        _err("usage: sadi-doctor fix CHECK-ID [--apply] [--yes] [--non-interactive]\n")
        return EXIT_USAGE
    try:
        got = fix(
            args.target,
            options,
            RealProbes(),
            _out,
            apply=args.apply,
            yes=args.yes,
            non_interactive=args.non_interactive,
        )
    except Exception:  # noqa: BLE001 - last resort: tell the user, exit 70
        _log.exception("doctor fix crashed")
        _err("sadi-doctor crashed; see the log. This is a bug in the doctor.\n")
        return EXIT_CRASH
    if not isinstance(got, Ok):
        _err(f"{got.unwrap_err().value}\n")
        return EXIT_USAGE
    return got.unwrap()


def _run(args: argparse.Namespace, options: RunOptions) -> int:
    """Run the checks, print the report and optionally write the bundle."""
    from sadi.doctor.bundle import capture_log, write_bundle  # lazy: bundle pulls sadi.store

    try:
        with capture_log() as captured:
            result = run(
                options, budget=_budget(args, options)
            )  # frob:ticket 01M6WJHW2KET2M1730MZVJ1X4E
    except Exception:  # noqa: BLE001 - last resort: tell the user, exit 70
        _log.exception("doctor crashed")
        _err("sadi-doctor crashed; see the log. This is a bug in the doctor.\n")
        return EXIT_CRASH
    if not isinstance(result, Ok):
        _err(f"{result.unwrap_err().value}\n")
        return EXIT_USAGE
    report = result.unwrap()
    if args.bundle:
        data_root = report.host.data_root
        assert data_root is not None, "run() always resolves the data root"
        wrote = write_bundle(report, captured.lines, Path(args.bundle), Path(data_root))
        if not isinstance(wrote, Ok):
            wrote_err = wrote.unwrap_err()
            _err(f"{wrote_err.value}\n")
            return EXIT_CRASH if wrote_err is DoctorError.BundleWriteFailed else EXIT_USAGE
        _err(f"bundle written: {wrote.unwrap()}\n")
    _out(
        report.model_dump_json(indent=2) + "\n"
        if args.json
        else render(report, verbose=args.verbose)
    )
    return exit_code(report)


if __name__ == "__main__":
    raise SystemExit(main())
